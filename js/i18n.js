function getNested(obj, path) {
  return path.split('.').reduce(function (o, k) {
    return o && o[k];
  }, obj);
}

function applyTranslations() {
  var lang = document.documentElement.classList.contains('ar') ? 'ar' : 'en';
  document.querySelectorAll('[data-i18n]').forEach(function (el) {
    var value = getNested(translations[lang], el.getAttribute('data-i18n'));
    if (typeof value === 'string') {
      el.textContent = value;
    }
  });
  document.querySelectorAll('[data-i18n-alt]').forEach(function (el) {
    var value = getNested(translations[lang], el.getAttribute('data-i18n-alt'));
    if (typeof value === 'string') {
      el.setAttribute('alt', value);
    }
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach(function (el) {
    var value = getNested(translations[lang], el.getAttribute('data-i18n-placeholder'));
    if (typeof value === 'string') {
      el.setAttribute('placeholder', value);
    }
  });
}

function updatePageTitle() {
  var meta = document.querySelector('meta[name="i18n-title"]');
  if (!meta) return;
  var lang = document.documentElement.classList.contains('ar') ? 'ar' : 'en';
  var value = getNested(translations[lang], meta.getAttribute('content'));
  if (typeof value === 'string') {
    document.title = value;
  }
}

function updateMetaDescription() {
  var meta = document.querySelector('meta[name="i18n-description"]');
  var descMeta = document.querySelector('meta[name="description"]');
  if (!meta || !descMeta) return;
  var lang = document.documentElement.classList.contains('ar') ? 'ar' : 'en';
  var value = getNested(translations[lang], meta.getAttribute('content'));
  if (typeof value === 'string') {
    descMeta.setAttribute('content', value);
  }
}

function setLang(lang) {
  var root = document.documentElement;
  var isAr = lang === 'ar';
  root.classList.toggle('ar', isAr);
  root.lang = isAr ? 'ar' : 'en';
  root.dir = isAr ? 'rtl' : 'ltr';
  try {
    localStorage.setItem('branch-lang', lang);
  } catch (e) {}
  document.querySelectorAll('[data-lang]').forEach(function (btn) {
    btn.setAttribute('aria-pressed', String(btn.getAttribute('data-lang') === lang));
  });
  applyTranslations();
  updatePageTitle();
  updateMetaDescription();
}

(function restoreLang() {
  var saved = null;
  try {
    saved = localStorage.getItem('branch-lang');
  } catch (e) {}
  if (saved !== 'ar' && saved !== 'en') {
    saved = document.documentElement.classList.contains('ar') ? 'ar' : 'en';
  }
  setLang(saved);
})();
